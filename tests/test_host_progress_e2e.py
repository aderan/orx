"""End-to-end stand-in acceptance of the G006 host-progress machinery.

Two continuous stories replay docs/host-progress-contract.md §10 (the frozen
recovery boundaries) with local stand-ins — dispatch calls double for the
worker and the Controller, a frozen ORX clock replaces every wait, so no paid
model runs and nothing really sleeps:

(a) claim -> explicit reports -> overdue CHECK HINT -> `orx run` recovery
    re-surface -> the ORIGINAL attempt's valid late delivery is accepted:
    the hint observed, it never acted;
(b) confirmed death -> explicit fail/retry -> a fresh report window -> the
    old attempt's late report AND late delivery are both rejected, its
    reports live on only as timeline history.

A final section pins the documentation to the machinery (contract §11):
README and both skills teach the explicit report discipline and the
bounded-wait / check-the-original-session-first rule without promoting the
channel as an automatic heartbeat, a liveness proof, or an automatic
recovery.
"""

