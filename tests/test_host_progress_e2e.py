def _negated(line_lower: str, phrase: str) -> bool:
    """True when every occurrence of phrase on the line is preceded by a
    negation (no/not/never) — a disclaimer, not a promotion."""
    index = line_lower.find(phrase)
    while index != -1:
        prefix = line_lower[:index].rstrip()
        if not prefix.endswith(("no", "not", "never")):
            return False
        index = line_lower.find(phrase, index + 1)
    return True


def test_no_doc_line_about_heartbeat_claims_savings_or_automation():
    """Contract §11 red lines, applied where they bind: no line mentioning
    the report channel may claim token/time savings, an automatic heartbeat,
    or a lease/keepalive. (The README's replan section legitimately mentions
    that an earlier token-savings claim was WITHDRAWN — a disclaimer about a
    different feature that never mentions the report channel.)"""
    for path in (
        REPO_ROOT / "README.md",
        REPO_ROOT / "skills" / "orx-agent" / "SKILL.md",
        REPO_ROOT / "skills" / "orx-controller" / "SKILL.md",
    ):
        for line in path.read_text().splitlines():
            if "heartbeat" not in line.lower():
                continue
            lower = line.lower()
            assert "token" not in lower, (path, line)
            assert "saving" not in lower, (path, line)
            assert _negated(lower, "automatic heartbeat"), (path, line)
            assert _negated(lower, "keepalive"), (path, line)
            assert _negated(lower, "lease"), (path, line)


