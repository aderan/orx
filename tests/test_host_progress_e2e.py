# A 1-minute report threshold so the overdue transition is a small, exact
# clock move (the comparison itself is contract §8: age >= timeout, closed).
PROGRESS_TIMEOUT_ONE_MIN = HOST_CONFIG_TOML.replace(
    '[worker]\nprofiles = ["host-worker", "host-external"]\n',
    '[worker]\nprofiles = ["host-worker", "host-external"]\n'
    "progress_timeout_min = 1\n",
)


def _freeze_orx_clock(monkeypatch):
    """Freeze both ORX clock seams (write and read side) at one instant."""
    holder = {"now": datetime(2026, 10, 6, 12, 0, 0, tzinfo=timezone.utc)}

    def now():
        return holder["now"].isoformat(timespec="microseconds")

    monkeypatch.setattr("orx.state.now", now)
    monkeypatch.setattr("orx.dispatch.db_now", now)
    return holder


@pytest.fixture
def e2e(tmp_path, monkeypatch):
    """A parked host task under a frozen ORX clock and a 1-minute report
    threshold. Yields (project, clock): advance clock["now"] instead of
    sleeping — every threshold comparison is arithmetic on the seam."""
    monkeypatch.chdir(tmp_path)
    clock = _freeze_orx_clock(monkeypatch)
    project = make_project(tmp_path, config_toml=PROGRESS_TIMEOUT_ONE_MIN)
    goal = dispatch.create_goal(
        project, objective="e2e progress acceptance",
        acceptance=["the stand-in loop closes safely"],
        constraints=[], context="",
    )[0]
    dispatch.submit_plan(project, ir_for(goal, [
        task_spec("T001", acceptance=goal.acceptance, verification=["true"]),
    ]))
    dispatch.run_slice(project)
    yield project, clock
    project.close()


def _progress_of(project, task_id="T001"):
    """The current-window progress block the task list publishes."""
    row = next(t for t in dispatch.task_list(project) if t["id"] == task_id)
    return row["progress"]


def _recovery_of(project, task_id="T001"):
    """The `orx run` recovery face for one running task."""
    return next(e for e in dispatch.run_slice(project)["recovery"]
                if e["task"] == task_id)


def _report_events(project, task_id="T001"):
    return [e for e in dispatch.timeline(project, task_id=task_id)["entries"]
            if e["event"] == "attempt.report"]


