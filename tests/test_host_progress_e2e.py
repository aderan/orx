# Scenario (a): reports, overdue hint, recovery re-surface, and the ORIGINAL
# attempt's valid late delivery still accepted (§10 bullet 2-3)


def test_scenario_a_overdue_hint_then_original_attempt_late_delivery(e2e, tmp_path):
    project, clock = e2e

    # The worker claims (session-bound so the hint can name its handle) and
    # works the assignment.
    claimed = dispatch.task_claim(project, "T001", session="sess-worker-a")
    attempt_id = claimed["attempt"]

    # Explicit progress reports at key phases (contract §2/§5): each response
    # names the attempt, a per-attempt sequence, and received_at generated by
    # the frozen ORX clock — never a client timestamp.
    first = dispatch.task_heartbeat(
        project, "T001", attempt_id, "exploring", "repo walked, plan holds",
    )
    assert first == {
        "task": "T001",
        "attempt": attempt_id,
        "sequence": 1,
        "phase": "exploring",
        "message": "repo walked, plan holds",
        "received_at": clock["now"].isoformat(timespec="microseconds"),
    }
    clock["now"] = clock["now"] + timedelta(seconds=20)
    second = dispatch.task_heartbeat(
        project, "T001", attempt_id, "checking", "round 1/3 red, fixing",
    )
    assert second["sequence"] == 2

    # The current window is fresh: reported, aged against the frozen clock.
    fresh = _progress_of(project)
    assert fresh["attempt"] == attempt_id
    assert fresh["state"] == "reported"
    assert fresh["phase"] == "checking"
    assert fresh["message"] == "round 1/3 red, fixing"
    assert fresh["age_sec"] == 0
    assert fresh["timeout_sec"] == 60  # configured 1 minute, in seconds
    assert fresh["hint"] is None and fresh["note"] is None

    # Long silence: age crosses the threshold and the window turns overdue.
    clock["now"] = clock["now"] + timedelta(seconds=90)
    attempts_before = len(project.store.attempts_all())
    events_before = len(project.store.task_events_all())

    recovery = _recovery_of(project)
    assert recovery["attempt"] == attempt_id
    assert recovery["session_ref"] == "sess-worker-a"
    progress = recovery["progress"]
    assert progress["attempt"] == attempt_id
    assert progress["state"] == "overdue"
    assert progress["phase"] == "checking"
    assert progress["age_sec"] == 90
    assert progress["timeout_sec"] == 60
    # The hint only advises: check the ORIGINAL session before any fail/retry.
    assert ">= 1m threshold" in progress["hint"]
    assert "check the original worker session" in progress["hint"]
    assert "handle: sess-worker-a" in progress["hint"]
    assert "before any fail/retry" in progress["hint"]
    # The recovery contract still binds late results to the attempt and keeps
    # the fail/retry door explicitly human.
    assert f"orx task complete T001 --attempt {attempt_id}" in recovery["contract"]
    assert "orx task fail T001" in recovery["contract"]
    assert "orx task retry T001" in recovery["contract"]

    # The overdue hint is observation only: nothing moved anywhere. Still
    # running, no new attempt, no extra task event, no second worker.
    assert active_task(project, "T001").status == "running"
    assert len(project.store.attempts_all()) == attempts_before
    assert len(project.store.task_events_all()) == events_before
    # The same overdue window rides status and the timeline's current block.
    assert dispatch.status_data(project)["tasks"][0]["progress"] == progress
    timeline = dispatch.timeline(project, task_id="T001")
    [current] = timeline["current"]
    assert current == {"task": "T001", "progress": progress}
    # Both reports are append-only history carrying the full identity.
    assert [e["detail"] for e in _report_events(project)] == [
        f"worker T001 a{attempt_id} #1 exploring — repo walked, plan holds",
        f"worker T001 a{attempt_id} #2 checking — round 1/3 red, fixing",
    ]

    # The ORIGINAL attempt's valid late delivery is accepted — overdue never
    # invalidated it. The completion passes its own gate ('true').
    result = dispatch.task_complete(
        project, "T001", str(write_evidence(tmp_path, "late.json")),
        attempt_id=attempt_id,
    )
    assert result["status"] == "passed"
    assert result["attempt"] == attempt_id
    assert dispatch.status_data(project)["run"]["status"] == "done"

    # The delivered attempt stays closed: one more report from it is refused
    # before any ownership question (the task is no longer running) — a
    # report never revives a delivered attempt — and the two recorded
    # reports survive as queryable history bound to it.
    late_report = _heartbeat_rejection(project, attempt_id)
    assert late_report.reason == "task_not_running"
    stored = project.store.attempt_progress_all(attempt_id)
    assert [r.sequence for r in stored] == [1, 2]
    assert len(_report_events(project)) == 2


def _heartbeat_rejection(project, attempt_id):
    """Run one heartbeat for a (dead) attempt and return the raised error so
    the story can pin the machine reason (contract §5) alongside the type."""
    with pytest.raises(ConflictError) as excinfo:
        dispatch.task_heartbeat(
            project, "T001", attempt_id, "checking", "late text",
        )
    return excinfo.value


# ---------------------------------------------------------------------------
# Scenario (b): confirmed death -> explicit fail/retry -> fresh window -> the
# old attempt's late report AND delivery both rejected (§10 bullet 4)


def test_scenario_b_confirmed_death_fail_retry_rejects_old_attempt(e2e, tmp_path):
    project, clock = e2e

    # Round 1 runs and reports, then goes overdue — the same observation as
    # scenario (a), compressed: the hint is the CHECK cue, not a verdict.
    claimed = dispatch.task_claim(project, "T001", session="sess-worker-b")
    old_attempt = claimed["attempt"]
    dispatch.task_heartbeat(
        project, "T001", old_attempt, "implementing", "mid-refactor",
    )
    clock["now"] = clock["now"] + timedelta(seconds=4000)
    overdue = _recovery_of(project)
    assert overdue["attempt"] == old_attempt
    assert overdue["progress"]["state"] == "overdue"
    assert "check the original worker session" in overdue["progress"]["hint"]

    # Death is confirmed by the human (the Controller here), never by ORX:
    # the explicit fail closes the attempt, the retry reopens the task.
    dispatch.task_fail(project, "T001", "original session confirmed dead")
    dispatch.task_retry(project, "T001")

    # A fresh round is parked (host_required, not recovery) and claimed —
    # a NEW attempt owns the task; the old one can never win it back.
    parked = [e for e in dispatch.run_slice(project)["host_required"]
              if e["task"] == "T001"]
    assert len(parked) == 1
    new_claim = dispatch.task_claim(project, "T001", session="sess-worker-b2")
    new_attempt = new_claim["attempt"]
    assert new_attempt != old_attempt

    # The new report window starts unknown: the old attempt's report never
    # fills it, on any face.
    window = _progress_of(project)
    assert window["attempt"] == new_attempt
    assert window["state"] == "unknown"
    assert window["phase"] is None and window["message"] is None
    assert window["received_at"] is None
    assert window["hint"] is None
    assert dispatch.status_data(project)["tasks"][0]["progress"] == window
    assert next(c["progress"] for c in
                dispatch.timeline(project)["current"]
                if c["task"] == "T001") == window

    # The OLD attempt's late report is rejected (closed attempt), while the
    # new attempt reports freely with its own sequence numbering.
    old_report = _heartbeat_rejection(project, old_attempt)
    assert old_report.reason == "attempt_closed"
    accepted = dispatch.task_heartbeat(
        project, "T001", new_attempt, "checking", "fresh window",
    )
    assert accepted["sequence"] == 1  # per-attempt sequences never carry over
    assert _progress_of(project) == {
        "attempt": new_attempt,
        "state": "reported",
        "phase": "checking",
        "message": "fresh window",
        "received_at": accepted["received_at"],
        "age_sec": 0,
        "timeout_sec": 60,
        "hint": None,
        "note": None,
    }

    # The OLD attempt's late delivery is rejected as stale: the retry moved
    # ownership, and no delivery from the closed attempt may close the task.
    with pytest.raises(ConflictError, match="stale"):
        dispatch.task_complete(
            project, "T001", str(write_evidence(tmp_path, "stale.json")),
            attempt_id=old_attempt,
        )
    assert active_task(project, "T001").status == "running"

    # The old attempt's report survives only as timeline history — never as
    # the current window, which shows the NEW attempt's report.
    events = _report_events(project)
    assert [e["detail"] for e in events] == [
        f"worker T001 a{old_attempt} #1 implementing — mid-refactor",
        f"worker T001 a{new_attempt} #1 checking — fresh window",
    ]
    current = next(c["progress"] for c in
                   dispatch.timeline(project)["current"]
                   if c["task"] == "T001")
    assert current["attempt"] == new_attempt
    assert current["state"] == "reported"
    assert current["phase"] == "checking"

    # The new attempt delivers normally and closes the loop.
    result = dispatch.task_complete(
        project, "T001", str(write_evidence(tmp_path, "round2.json")),
        attempt_id=new_attempt,
    )
    assert result["status"] == "passed"
    assert result["attempt"] == new_attempt
    assert dispatch.status_data(project)["run"]["status"] == "done"
    # History intact after the pass: both attempts' reports stay queryable.
    assert [r.sequence for r in project.store.attempt_progress_all(old_attempt)] == [1]
    assert [r.sequence for r in project.store.attempt_progress_all(new_attempt)] == [1]
    assert len(_report_events(project)) == 2


