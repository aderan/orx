# T004: the local stand-in Goal loop, outside the repo, through the
# installed CLI (planning, execution, structured delivery, verdict)


def test_stand_in_goal_loop_closes_with_structured_delivery(chain):
    standin = chain["cli"]["standin"]
    # Planning: one plan revision with two tasks; one active Goal throughout.
    assert standin["revision"] == 1 and standin["plan_tasks"] == 2
    assert standin["single_goal_after_plan"] is True
    assert standin["final_single_goal"] is True
    # Execution: host work is PARKED (no paid model, no analytics).
    assert standin["t001_parked"] == ["T001"]
    assert standin["heartbeat_sequence"] == 1
    # The legacy {summary, commands, artifacts} shape is rejected by name…
    rejection = standin["legacy_rejection"]
    assert rejection["exit_code"] == 1
    assert rejection["ok"] is False
    for token in ("evidence rejected", "'status'", "'checks'"):
        assert token in rejection["error"]
    # …and the rejection changed nothing: the task kept running.
    assert standin["t001_status_after_rejection"] == "running"
    # The structured delivery result is accepted, verified independently.
    assert standin["t001_after_complete"] == "verifying"
    assert standin["agent_entries"] == [check_release.STANDIN_AGENT_ENTRY]
    assert standin["t001_verdict_status"] == "passed"
    assert standin["t002_parked"] == ["T002"]
    assert standin["t002_after_complete"] == "passed"
    assert standin["final_run_status"] == "done"
    assert standin["final_task_statuses"] == {"T001": "passed", "T002": "passed"}
    # Exit codes: 1 for the rejected delivery, 2 for a click usage error.
    assert standin["usage_error_exit_code"] == 2


