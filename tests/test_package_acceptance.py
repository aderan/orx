# The three roles install FROM THE PACKAGE through the preset


def test_clean_install_preset_installs_all_three_roles_from_the_package(installed):
    report = installed["report"]
    agents = report["preset_fresh"]["agents"]
    for name in check_release.NATIVE_AGENTS:
        row = agents[name]
        # Installed, and no "install manually" note — the 0.3.0 symptom.
        assert row["installed"] is True, (name, row)
        assert row["note"] is None, (name, row)
    # The installed files are byte-identical to the packaged copies: the
    # content provably came from the wheel, not from some repo fallback.
    assert report["preset_fresh"]["installed_contents_match_package"] == {
        "orx-worker": True,
        "orx-verifier": True,
        "orx-verifier-strong": True,
    }
    assert set(report["preset_fresh"]["profiles_added"]) == {
        "zcode-controller", "zcode-worker",
        "zcode-verifier-flash", "zcode-verifier-strong",
    }


def test_preset_from_the_package_preserves_existing_role_definitions(installed):
    """The preserve regression at package level: a live custom definition
    wins over the packaged one — the preset never silently replaces an
    existing role file (updates are explicit, per docs/upgrade-0.3.1.md)."""
    report = installed["report"]
    preserve = report["preset_preserve"]
    worker = preserve["agents"]["orx-worker"]
    assert worker["installed"] is False
    assert worker["preserved_existing"] is True
    assert preserve["custom_content_intact"] is True
    for name in ("orx-verifier", "orx-verifier-strong"):
        assert preserve["agents"][name]["installed"] is True


