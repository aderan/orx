# T004: the upgrade chain on a copy of the fixture (docs/upgrade-0.3.1.md §6)


def test_upgrade_preserves_every_v8_row_and_adds_only_defaults(chain):
    upgrade = chain["upgrade"]
    assert upgrade["problems"] == []
    assert upgrade["upgraded_schema_version"] == 11
    checked = upgrade["identity"]["tables_checked"]
    for table in check_release.V8_CORE_TABLES:
        assert table in checked, table
        assert checked[table]["rows"] > 0, table
        assert checked[table]["columns"] > 0, table
    # Row-by-row identity covered a meaningful slice of the sample.
    assert upgrade["identity"]["rows_compared"] >= 15
    # The in-flight task is still there, attempt rows intact.
    assert checked["attempts"]["rows"] >= 3


def test_real_v030_rejects_upgraded_db_and_backup_restores(chain):
    upgrade = chain["upgrade"]
    assert upgrade["problems"] == []
    # The read entry used for rejection really was the old version.
    assert upgrade["old_version_reported"] == "0.3.0"
    rejection = upgrade["old_rejection"]
    assert rejection["exit_code"] == 1
    assert "newer than supported version 8" in rejection["output_tail"]
    # The §6.1 backup exists, restores, and the old version reads it back.
    backup = next(s for s in upgrade["steps"]
                  if s["step"] == "backup-vacuum-into")
    assert backup["bytes"] > 0
    assert upgrade["restore"]["exit_code"] == 0
    assert upgrade["restore"]["goal_read_back"] is True
    # The source sample was never modified by any of it.
    sha = upgrade["source_sha256"]
    assert sha["before"] == sha["after"]
    assert sha["after"] == chain["structure"]["sha256"]
