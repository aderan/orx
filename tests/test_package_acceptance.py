# T004: the real v0.3.0 schema-v8 fixture and its provenance


def test_fixture_is_a_genuine_non_trivial_v030_v8_sample(chain):
    structure = chain["structure"]
    assert chain["struct_problems"] == []
    assert structure["schema_version"] == 8
    # The v9+ tables and the v11 column do not exist yet in the sample.
    assert not set(check_release.V11_ADDITIVE_TABLES) & set(structure["tables"])
    # Core v8 tables carry real data (an empty fixture would prove nothing).
    for table in check_release.V8_CORE_TABLES:
        assert structure["tables"][table] > 0, table
    # The local tag still points at the provenance commit.
    assert structure["tag_commit"] == check_release.V030_COMMIT
    # The committed file is exactly what the real v0.3.0 code produces.
    assert chain["provenance"]["problems"] == []
    assert chain["provenance"]["matches_regeneration"] is True


