"""Package-level acceptance (G007 T001 + T004): judge the BUILT wheel, not
the source tree.

The 0.3.1 gap this pins: ``[tool.hatch.build.targets.wheel]`` shipped
``orx/skills`` but not ``orx/agents``, so on a clean (non-editable)
install ``presets.source_agents_dir()`` fell back to a repo layout that
does not exist inside site-packages and ``orx preset install zcode``
reported every native role as "definition not packaged with this ORX
(install manually)". The regression here builds the wheel, installs it
into a throwaway venv, and proves — from OUTSIDE the repository — that:

- ``orx`` imports from the temporary site-packages (never the repo or an
  editable copy), with the probe's working directory outside the repo and
  a sanitized environment (no PYTHONPATH, isolated ORX_* layer);
- the three native ZCode role definitions (orx-worker, orx-verifier,
  orx-verifier-strong) ship in the wheel and install through the packaged
  preset with no "install manually" note, byte-identical to the packaged
  copies — the roles come from the installed package;
- the packaged default skills are present in the wheel the same way;
- the preset still never overwrites a live definition (a pre-existing
  custom orx-worker.md stays untouched; the missing roles still install):
  the update path for existing role files is explicit and documented in
  docs/upgrade-0.3.1.md, not a silent replacement.

T004 extends the same wheel install to the full release story (all via
the INSTALLED console script, never the source tree, and with no skip):

- the user layer through the CLI: preset install (fresh + preserve),
  EVERY packaged skill installed, one drifted and refreshed by
  ``orx skill update`` from the package;
- a local stand-in Goal outside the repo: init -> goal -> plan submit ->
  run parks host work (no paid model, no analytics, quota preflight off)
  -> claim -> heartbeat -> the legacy {summary, commands, artifacts}
  evidence shape REJECTED by name (exit 1, task untouched) -> the
  structured delivery result accepted -> an independent verdict via
  ``orx verify submit`` -> run done; --json envelopes and exit codes 0/1/2
  asserted throughout;
- the real v0.3.0 schema-v8 fixture (tests/fixtures/release-0.3.0,
  generated by the actual v0.3.0 code from the git tag — proven by
  regenerating and comparing normalized logical dumps): a copy is backed
  up (VACUUM INTO), upgraded to v11 by the installed new version, checked
  row-by-row across every pre-existing table and column, additive
  defaults verified (new tables empty, legacy nonces NULL), the REAL
  v0.3.0 read entry refuses the v11 file without modifying it, and the
  backup restores and reads back under the real v0.3.0 code. The source
  fixture stays byte-identical (sha256 asserted).

The build/install/probe mechanics live in ``scripts/check_release.py``
(one wheel build + one venv per module, shared by the tests here and by
the standalone release check). The fast source pin of the packaging
config itself is in tests/test_phase_c.py. The run book describing
entries, dependencies, fixture provenance and failure behavior is
docs/package-acceptance.md.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
FIXTURE_DIR = REPO_ROOT / "tests" / "fixtures" / "release-0.3.0"


def _load_check_release():
    spec = importlib.util.spec_from_file_location(
        "check_release", REPO_ROOT / "scripts" / "check_release.py"
    )
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


check_release = _load_check_release()


@pytest.fixture(scope="module")
def installed(tmp_path_factory):
    """One wheel build + one clean venv install + one probe run, shared by
    every test in this module (the expensive part of the acceptance)."""
    workdir = tmp_path_factory.mktemp("orx-package-acceptance")
    wheel = check_release.build_wheel(workdir / "dist", REPO_ROOT)
    python = check_release.install_wheel(wheel, workdir / "venv")
    report = check_release.run_probe(python, workdir / "scratch")
    return {
        "workdir": workdir,
        "wheel": wheel,
        "python": python,
        "report": report,
    }


@pytest.fixture(scope="module")
def chain(installed):
    """The T004 sections, run once against the same wheel install: the CLI
    user-layer flow (preset + skills + the stand-in Goal) and the v0.3.0
    fixture chain (structure, upgrade, old-version rejection, backup
    restore, regeneration provenance)."""
    workdir = installed["workdir"]
    orx_bin = installed["python"].parent / "orx"
    cli = check_release.run_cli_flow(installed["python"], workdir / "cli-flow")
    structure, struct_problems = check_release.check_fixture_structure(
        FIXTURE_DIR, REPO_ROOT)
    upgrade = check_release.check_upgrade_chain(
        FIXTURE_DIR, installed["python"], orx_bin, workdir / "upgrade", REPO_ROOT)
    provenance = check_release.verify_fixture_provenance(
        FIXTURE_DIR, REPO_ROOT, installed["python"], workdir / "regen")
    return {
        "cli": cli,
        "structure": structure,
        "struct_problems": struct_problems,
        "upgrade": upgrade,
        "provenance": provenance,
    }


