def test_cli_installs_preset_and_every_packaged_skill(chain):
    cli = chain["cli"]
    # Preset, fresh install: every native role from the package.
    rows = {row["name"]: row for row in cli["preset_fresh"]["agents"]}
    for name in check_release.NATIVE_AGENTS:
        assert rows[name]["installed"] is True
        assert rows[name].get("note") is None
    # Preserve case: a live custom definition wins, untouched.
    preserved = {row["name"]: row for row in cli["preset_preserve"]["agents"]}
    assert preserved["orx-worker"]["preserved_existing"] is True
    # Every packaged skill installs (the repo ships three).
    assert sorted(cli["packaged_skills"]) == [
        "orx-agent", "orx-controller", "orx-pbv",
    ]
    assert sorted(cli["skills"]["installed"]) == sorted(cli["packaged_skills"])
    # The canonical root and the symlinks stay inside the isolated HOME.
    home = Path(cli["skills"]["canonical_root"]).parent.parent
    assert Path(cli["skills"]["canonical_root"]).is_relative_to(home)
    for target in cli["skills"]["symlinked_into"]:
        assert Path(target).is_relative_to(home)
    # A drifted skill refreshes from the packaged copy, byte-identical.
    assert "orx-controller" in cli["skills"]["refreshed"]
    assert cli["skills"]["refresh_matches_package"] is True


