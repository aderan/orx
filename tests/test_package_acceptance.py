# Clean install: imports and resources come from the temporary package


def test_probe_ran_outside_the_repo_from_temp_site_packages(installed):
    report = installed["report"]
    # The probe's own working directory is the scratch dir (not the repo).
    assert not Path(report["probe_cwd"]).resolve().is_relative_to(REPO_ROOT)
    # orx itself imports from the throwaway venv's site-packages.
    assert report["orx_in_site_packages"]
    orx_file = Path(report["orx_file"])
    assert orx_file.is_relative_to(Path(report["site_packages"]))
    assert not orx_file.is_relative_to(REPO_ROOT)
    assert not installed["workdir"].is_relative_to(REPO_ROOT)


def test_wheel_ships_native_agent_definitions_and_default_skills(installed):
    report = installed["report"]
    assert report["agents_in_site_packages"], report["agents_source"]
    assert report["agents_present"] == {
        "orx-worker": True, "orx-verifier": True, "orx-verifier-strong": True,
    }
    assert report["skills_in_site_packages"], report["skills_source"]
    assert report["skills_present"] == {
        "orx-controller": True, "orx-agent": True,
    }


